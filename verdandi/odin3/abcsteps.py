"""Odin III's ``abc`` pass opened up into graph transformations (spec 6a).

The pass hands each module's soft logic (one run per clock domain) to linked ABC with the
script ``lib/abc/vtr.abc``. Verdandi runs the same exchange on a copy of the design
(``abc --lut K --via-blif DIR`` writes ``abc<N>.in.blif`` per run), then replays the script's
commands on that BLIF with the standalone ABC binary, one process per command prefix, so each
command has the numbers, the picture and the network ABC itself produced.

The dot files are ABC's ``write_dot`` bytes with its leading comment header dropped: ABC
starts the file with ``# Network structure generated by ABC``, and the step's picture is the
``digraph`` alone.
"""

from __future__ import annotations

import os
import re
import subprocess
from collections.abc import Iterable
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    import odin3

# The spec's fallback when the source tree has no lib/abc/vtr.abc (spec 6a).
_FALLBACK: tuple[str, ...] = (
    "strash",
    "ifraig -v",
    "scorr -v",
    "dc2 -v",
    "dch -f",
    "if -K {K} -v",
    "mfs2 -v",
)

TITLES: dict[str, str] = {
    "strash": "AIG: structural hashing",
    "ifraig": "Merge equivalent nodes",
    "scorr": "Merge equivalent registers",
    "dc2": "Rewrite and balance",
    "dch": "Rewrite with choices",
    "if": "K-LUT technology mapping (cuts and cover)",
    "mfs2": "Simplify LUTs with don't-cares",
}

# An exchange run's BLIF input file: abc<N>.in.blif (src/passes/abc/run.c k_file_suffix).
_INPUT_FILE = re.compile(r"abc(\d+)\.in\.blif")

# The print_stats fields (spec 6a): i/o, lat, and or nd, lev, and edge when present.
_STAT_KEYS = ("lat", "and", "nd", "lev", "edge")

# ANSI colour codes ABC puts around the network name; the trace's log is plain text.
_ANSI = re.compile(r"\x1b\[[0-9;]*m")


@dataclass
class AbcStep:
    """One ABC command's result: its numbers, its picture and the network it made."""

    command: str
    stats: dict[str, int]
    dot: Path
    blif: Path
    log: list[str]


def find_abc(odin3_root: Path | None) -> str | None:
    """The standalone ABC binary: $ODIN3_ABC, else build/*/third_party/abc/abc (spec 9)."""
    configured = os.environ.get("ODIN3_ABC")
    if configured:
        path = Path(configured)
        if path.is_file() and os.access(path, os.X_OK):
            return str(path)
    if odin3_root is None:
        return None
    found = sorted(
        odin3_root.glob("build/*/third_party/abc/abc"),
        key=lambda path: (path.parent.parent.parent.name != "release", str(path)),
    )
    for candidate in found:
        if candidate.is_file() and os.access(candidate, os.X_OK):
            return str(candidate)
    return None


def abc_script(odin3_root: Path | None, k: int) -> list[str]:
    """The commands of lib/abc/vtr.abc (comments and blank lines dropped, ``{K}`` replaced).

    Without the source file, the spec 6a fallback list. The final ``print_stats`` is dropped:
    ``run_abc_steps`` adds one after every command.
    """
    commands: list[str] = []
    if odin3_root is not None:
        try:
            text = (odin3_root / "lib" / "abc" / "vtr.abc").read_text(encoding="utf-8")
        except OSError:
            text = ""
        for line in text.splitlines():
            command = line.strip()
            if command and not command.startswith("#"):
                commands.append(command)
    if not commands:
        commands = list(_FALLBACK)
    commands = [command.replace("{K}", str(k)) for command in commands]
    if commands and commands[-1] == "print_stats":
        commands.pop()
    return commands


def capture_abc_input(design: odin3.Design, k: int, workdir: Path) -> list[Path]:
    """The BLIF files the real ``abc`` pass would exchange, from a copy of ``design``.

    One file per module and clock domain: the pass writes ``abc<N>.in.blif`` into its
    ``--via-blif`` directory (src/passes/abc/run.c, ``choose_dir`` and ``run_paths``), in run
    order. The copy is closed before returning; the design is left unchanged. An earlier
    capture's runs are removed first: the pass writes no file for a module with nothing to
    map, and those runs must not resurface as this capture's input.
    """
    workdir.mkdir(parents=True, exist_ok=True)
    for stale in workdir.glob("abc*.in.blif"):
        if _INPUT_FILE.fullmatch(stale.name) is not None:
            stale.unlink()
    copy = design.copy()
    try:
        with copy.odin3.capture_log():
            copy.run_pass("abc", f"--lut {k} --via-blif {workdir}")
    finally:
        copy.close()
    runs: list[tuple[int, Path]] = []
    for path in workdir.glob("abc*.in.blif"):
        match = _INPUT_FILE.fullmatch(path.name)
        if match is not None:
            runs.append((int(match.group(1)), path))
    return [path for _number, path in sorted(runs)]


def run_abc_steps(abc: str, blif: Path, commands: list[str], workdir: Path) -> list[AbcStep]:
    """Run ``commands`` on ``blif`` one prefix at a time, ABC's own output for each step.

    For command N one ABC process runs ``read_blif; cmd1; ...; cmdN; print_stats; write_dot
    sN.dot; write_blif sN.blif``, so the numbers, the picture and the network are ABC's, taken
    at exactly the state after command N. ABC exits 0 even when a command fails, so a missing
    dot or network file is the failure signal.
    """
    workdir.mkdir(parents=True, exist_ok=True)
    steps: list[AbcStep] = []
    for number in range(1, len(commands) + 1):
        dot = workdir / f"s{number}.dot"
        network = workdir / f"s{number}.blif"
        dot.unlink(missing_ok=True)
        network.unlink(missing_ok=True)
        script = "; ".join(
            [
                f"read_blif {_quoted(blif)}",
                *commands[:number],
                "print_stats",
                f"write_dot {_quoted(dot)}",
                f"write_blif {_quoted(network)}",
            ]
        )
        completed = subprocess.run(
            [abc, "-c", script], stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
            text=True, check=False,
        )
        log = [_ANSI.sub("", line) for line in completed.stdout.splitlines()]
        if not dot.is_file() or not network.is_file():
            tail = "; ".join(log[-3:]) if log else f"exit status {completed.returncode}"
            raise RuntimeError(f"abc command '{commands[number - 1]}' failed: {tail}")
        _drop_dot_header(dot)
        steps.append(
            AbcStep(
                command=commands[number - 1],
                stats=_parse_stats(log),
                dot=dot,
                blif=network,
                log=log,
            )
        )
    return steps


def _quoted(path: Path) -> str:
    """One ABC file argument, double-quoted (a temp path cannot hold a quote)."""
    return f'"{path}"'


def _drop_dot_header(path: Path) -> None:
    """Rewrite ABC's dot file from its first ``digraph`` line: the comment header is noise."""
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    while lines and (not lines[0].strip() or lines[0].lstrip().startswith("#")):
        lines.pop(0)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def _parse_stats(log: list[str], *, first: bool = False) -> dict[str, int]:
    """The ``print_stats`` numbers of a run: i/o as ``i`` and ``o``, and the named fields.

    A replay's log holds one ``print_stats`` line, read from its end; a linked pass's log holds
    one line per exchange run, and the replay follows run 0, so the recorder reads the first.
    """
    lines: Iterable[str] = log if first else reversed(log)
    for line in lines:
        if "i/o" not in line:
            continue
        stats: dict[str, int] = {}
        match = re.search(r"i/o\s*=\s*(\d+)/\s*(\d+)", line)
        if match is not None:
            stats["i"], stats["o"] = int(match.group(1)), int(match.group(2))
        for key in _STAT_KEYS:
            found = re.search(rf"\b{key}\s*=\s*(\d+)", line)
            if found is not None:
                stats[key] = int(found.group(1))
        return stats
    return {}
